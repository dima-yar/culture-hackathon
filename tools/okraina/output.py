"""Writes generated JS modules."""

import json

from .config import OUTPUT_DIR


def write_module(name, export_name, data, comment):
    write_exports(name, {export_name: data}, comment)


def write_exports(name, exports, comment):
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    body = '\n'.join(
        f'export const {export_name} = {json.dumps(data, ensure_ascii=False, separators=(",", ":"))};'
        for export_name, data in exports.items()
    )
    text = (
        f'/**\n * {comment}\n * Generated by tools/import-okraina.py from the Okraina project — do not edit by hand.\n */\n\n'
        f'{body}\n'
    )
    path = OUTPUT_DIR / name
    path.write_text(text, encoding='utf-8')
    print(f'{path.relative_to(OUTPUT_DIR.parent.parent.parent)}  {len(text) // 1024} KB')
